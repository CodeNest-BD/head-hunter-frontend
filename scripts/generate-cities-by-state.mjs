/**
 * Regenerates `src/shared/data/usCitiesByState.ts` from the client-supplied city
 * list at `requirements/usa-cities/usa_cities_by_state.csv`. Cities are grouped
 * by USPS state code, de-duplicated, and sorted alphabetically — this is the
 * canonical set the live-map state/city filters (and every city dropdown) offer.
 *
 * Run: `npm run generate:cities` (or `node scripts/generate-cities-by-state.mjs`).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const csvPath = join(root, "requirements/usa-cities/usa_cities_by_state.csv");
const outPath = join(root, "src/shared/data/usCitiesByState.ts");

/** Minimal RFC-4180 CSV line parser (handles quoted fields with commas). */
function parseLine(line) {
  const out = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"') {
        if (line[i + 1] === '"') {
          field += '"';
          i += 1;
        } else {
          inQuotes = false;
        }
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ",") {
      out.push(field);
      field = "";
    } else {
      field += ch;
    }
  }
  out.push(field);
  return out;
}

const raw = readFileSync(csvPath, "utf8").replace(/^﻿/, "");
const lines = raw.split(/\r?\n/).filter((l) => l.trim() !== "");
const header = parseLine(lines[0]).map((h) => h.trim());
const cityIdx = header.indexOf("City");
const codeIdx = header.indexOf("State Code");
if (cityIdx === -1 || codeIdx === -1) {
  throw new Error(`Unexpected CSV header: ${header.join(", ")}`);
}

/** @type {Map<string, Set<string>>} */
const byState = new Map();
for (let i = 1; i < lines.length; i += 1) {
  const cols = parseLine(lines[i]);
  const city = (cols[cityIdx] ?? "").trim();
  const code = (cols[codeIdx] ?? "").trim().toUpperCase();
  if (!city || !/^[A-Z]{2}$/.test(code)) continue;
  if (!byState.has(code)) byState.set(code, new Set());
  byState.get(code).add(city);
}

const codes = [...byState.keys()].sort();
let totalCities = 0;

let body = "";
for (const code of codes) {
  const cities = [...byState.get(code)].sort((a, b) =>
    a.localeCompare(b, "en-US"),
  );
  totalCities += cities.length;
  body += `  ${code}: [\n`;
  for (const city of cities) {
    body += `    ${JSON.stringify(city)},\n`;
  }
  body += `  ],\n`;
}

const out = `// GENERATED by scripts/generate-cities-by-state.mjs — do not edit by hand.
// Source: requirements/usa-cities/usa_cities_by_state.csv (client-supplied).
// Every city per state, keyed by USPS code, alphabetical. This is the canonical
// set the live-map state/city filters and every city dropdown offer.
// Lazy-loaded via dynamic import — keep out of the initial bundle.

export const US_CITIES_BY_STATE: Readonly<Record<string, readonly string[]>> = {
${body}};
`;

writeFileSync(outPath, out);
console.log(
  `Wrote ${outPath} — ${codes.length} states, ${totalCities} cities.`,
);
