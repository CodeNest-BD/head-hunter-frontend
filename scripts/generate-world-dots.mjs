/**
 * Build-time generator for the hero's dotted world map. Projects real world
 * geodata (world-atlas) through d3-geo, samples a grid of dots that fall on
 * land, and emits a single SVG path plus projected city coordinates to
 * `src/shared/data/worldDots.ts`. Run: `node scripts/generate-world-dots.mjs`.
 *
 * Emitting a path (not thousands of <circle> nodes) keeps the rendered hero a
 * handful of DOM nodes while staying fully vector — crisp at any size.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { geoEqualEarth, geoContains } from "d3-geo";
import { feature } from "topojson-client";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const topo = JSON.parse(
  readFileSync(join(root, "node_modules/world-atlas/countries-110m.json")),
);
const countries = feature(topo, topo.objects.countries);
// Drop Antarctica (id "010") — the reference map omits it, and it would push
// the whole map up to make room for an empty white band.
const land = {
  type: "FeatureCollection",
  features: countries.features.filter((f) => f.id !== "010"),
};

const W = 1200;
const H = 560;
const PAD = 16;
const projection = geoEqualEarth().fitExtent(
  [
    [PAD, PAD],
    [W - PAD, H - PAD],
  ],
  land,
);

// Grid sampling. STEP controls dot density; R is the dot radius.
const STEP = 12;
const R = 2.2;
const round = (n) => Math.round(n * 10) / 10;

let path = "";
let dotCount = 0;
for (let y = STEP / 2; y < H; y += STEP) {
  for (let x = STEP / 2; x < W; x += STEP) {
    const lnglat = projection.invert([x, y]);
    if (!lnglat) continue;
    if (!geoContains(land, lnglat)) continue;
    const cx = round(x);
    const cy = round(y);
    // A filled circle drawn as two arcs, appended to one path.
    path += `M${round(cx - R)},${cy}a${R},${R} 0 1,0 ${R * 2},0a${R},${R} 0 1,0 ${-R * 2},0`;
    dotCount += 1;
  }
}

const CITIES = [
  { name: "San Francisco", lng: -122.42, lat: 37.77, roles: 213 },
  { name: "New York", lng: -74.0, lat: 40.71, roles: 432, active: true },
  { name: "São Paulo", lng: -46.63, lat: -23.55, roles: 168 },
  { name: "London", lng: -0.13, lat: 51.51, roles: 278 },
  { name: "Johannesburg", lng: 28.05, lat: -26.2, roles: 142 },
  { name: "Bangkok", lng: 100.5, lat: 13.75, roles: 321 },
  { name: "Sydney", lng: 151.21, lat: -33.87, roles: 189 },
];

const cities = CITIES.map((c) => {
  const [x, y] = projection([c.lng, c.lat]);
  return {
    name: c.name,
    roles: c.roles,
    active: c.active ?? false,
    x: round(x),
    y: round(y),
  };
});

const out = `// GENERATED by scripts/generate-world-dots.mjs — do not edit by hand.
// A dotted world map (${dotCount} land dots) projected with d3-geoEqualEarth,
// emitted as one SVG path so the hero stays vector-crisp at any size.

export const HERO_VIEWBOX = { width: ${W}, height: ${H} } as const;

export const HERO_DOT_RADIUS = ${R};

export interface HeroCity {
  readonly name: string;
  readonly roles: number;
  readonly active: boolean;
  /** Position in HERO_VIEWBOX units. */
  readonly x: number;
  readonly y: number;
}

export const HERO_CITIES: readonly HeroCity[] = ${JSON.stringify(cities, null, 2)};

export const HERO_DOTS_PATH =
  ${JSON.stringify(path)};
`;

writeFileSync(join(root, "src/shared/data/worldDots.ts"), out);
console.log(
  `Wrote src/shared/data/worldDots.ts — ${dotCount} dots, ${cities.length} cities.`,
);
